import fs from 'node:fs';
import path from 'node:path';
import {SqliteStore} from '../lib/sqlite-store.ts';
import {validateEvents} from '../lib/store-events.ts';
const [input,output]=process.argv.slice(2);
if(!input||!output||!['.sqlite','.db'].includes(path.extname(output)))throw new Error('Usage: npm run data:restore -- backup.json new-database.sqlite');
const backup=JSON.parse(fs.readFileSync(input,'utf8'));
if(!['dsi-events-backup/1','dsi-json-store/1'].includes(backup.schema))throw new Error('Unsupported backup format. Use a full-history export.');
validateEvents(backup.events);
await new SqliteStore(output).restoreEvents(backup.events);
console.log(`Restored ${backup.events.length} events with original IDs, actors, timestamps, and versions into ${path.resolve(output)}. Existing files were not overwritten.`);
