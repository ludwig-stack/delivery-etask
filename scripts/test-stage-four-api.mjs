import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
const base=process.env.DSI_TEST_URL;
assert(base&&new URL(base).hostname==='127.0.0.1','Use an isolated local database.');
let checks=0;
async function call(path,cookie,body,status=200){
 const response=await fetch(base+path,{method:body?'POST':'GET',headers:{...(cookie?{Cookie:cookie}:{}),...(body?{'Content-Type':'application/json',Origin:base}:{})},...(body?{body:JSON.stringify(body)}:{})});
 const data=await response.json();assert.equal(response.status,status,`${path}: ${JSON.stringify(data)}`);checks++;return {data,cookie:response.headers.get('set-cookie')?.split(';')[0]};
}
const login=async(email,password)=>(await call('/api/auth/login',null,{email,password})).cookie;
const admin=await login('qa-admin',process.env.DSI_TEST_ADMIN_PASSWORD);
const staff=await login('stage-staff',process.env.DSI_STAGE_PASSWORD);
const viewer=await login('stage-viewer',process.env.DSI_STAGE_PASSWORD);
const native=fs.readFileSync('.local-accounts.txt','utf8').split('\n').find(l=>l.includes(': wyline@local.test / '));assert(native);
const reviewer=await login('wyline@local.test',native.split(' / ')[1].trim());
const id=`CUSTOM-${crypto.randomUUID()}`;
const task={title:'Stage 4 check',owner:'Joey',startDate:'2026-10-24',date:'2026-10-26',workstream:'QA',deliverable:'Output',acceptance:'Verified',status:'Ready',target:''};
let record=(await call('/api/state',admin,{entityType:'task',entityId:id,version:0,data:task})).data.value;
const write=async(cookie,data,status=200,version=record.version)=>call('/api/state',cookie,{entityType:'task',entityId:id,version,data},status);
for(const patch of [{title:'Unauthorized'},{acceptance:'Unauthorized'},{startDate:'2026-10-25'},{date:'2026-10-27'}])await write(staff,{...record,...patch},403);
await write(admin,{...record,startDate:'2026-10-27'},400);
await write(admin,{...record,startDate:'2027-01-01'},400);
record=(await write(reviewer,{...record,title:'Reviewer title',acceptance:'Reviewer requirements',startDate:'2026-10-25',date:'2026-10-27'})).data.value;
assert.equal(record.title,'Reviewer title');assert.equal(record.startDate,'2026-10-25');assert.equal(record.date,'2026-10-27');
record=(await write(staff,{...record,status:'In progress',notes:'Staff working note'})).data.value;
await write(viewer,{action:'comment',text:'Read only'},403);
record=(await write(staff,{action:'comment',text:'Staff comment',authorName:'Forged',at:'fake'})).data.value;
const comment=record.comments[0];assert.equal(comment.authorName,'Stage staff');assert(Number.isFinite(Date.parse(comment.at)));
assert.equal(record.notes,'Staff working note');assert.equal(record.acceptance,'Reviewer requirements');
await write(admin,{action:'comment',text:'Stale'},409,record.version-1);
await write(admin,{action:'comment',text:'Reply',parentId:'missing'},400);
record=(await write(reviewer,{action:'comment',text:'Reviewer reply',parentId:comment.id})).data.value;
assert.equal(record.comments[1].parentId,comment.id);
record=(await write(admin,{...record,title:'Admin title',comments:[]})).data.value;
assert.equal(record.comments.length,2,'Saving edits cannot erase comment history.');
const reloaded=(await call('/api/state',staff)).data.overrides[id];
assert.equal(reloaded.title,'Admin title');assert.deepEqual(reloaded.comments,record.comments);
console.log(`Stage 4: ${checks} isolated local API checks passed.`);
